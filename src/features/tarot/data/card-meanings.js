export const CARD_MEANINGS = new Map(
  entries.map(([id, overview, upright, reversed]) => {
    const [family, rawNumber] = id.split("-");
    return [
      id,
      Object.freeze({
        number: family === "major" ? rawNumber : rawNumber.replace(/^0/, ""),
        arcana: family === "major" ? "大阿卡那 · MAJOR ARCANA" : suitLabels[family],
        overview,
        upright,
        reversed,
      }),
    ];
  }),
);

if (CARD_MEANINGS.size !== DECK.length || DECK.some((card) => !CARD_MEANINGS.has(card.id)))
  throw new Error("Every tarot card must have a complete meaning");
